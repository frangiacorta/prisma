export function pouchWeight(release) {
 const step=(a,b,x)=>{const t=Math.max(0,Math.min(1,(x-a)/(b-a)));return t*t*(3-2*t);};
 return step(.026,.077,release)*(1-step(.25,.54,release));
}

export function pouchPosition(row,release) {
 const load=pouchLoads, count=load.length;
 const sample=(index,axis)=>row[2*index+axis];
 if(release<=load[0])return row.slice(0,2);
 if(release>=load[count-1])return row.slice(2*count-2,2*count);
 let i=0;
 while(release>load[i+1])i++;
 const span=load[i+1]-load[i],u=(release-load[i])/span,ii=Math.max(0,i-1),jj=Math.min(count-1,i+2);
 return [0,1].map(axis=>{
  const a=sample(i,axis),b=sample(i+1,axis),da=(b-sample(ii,axis))*span/(load[i+1]-load[ii]),db=(sample(jj,axis)-a)*span/(load[jj]-load[i]);
  return a+(b-a)*u*u*(3-2*u)+u*(1-u)*((1-u)*da-u*db);
 });
}
